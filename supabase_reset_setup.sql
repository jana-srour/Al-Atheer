  id uuid primary key references auth.users (id) on delete cascade,
  display_name text not null default '',
  is_admin boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.admin_email_invites (
  email text primary key,
  added_by uuid not null references auth.users (id),
  created_at timestamptz not null default now(),
  constraint admin_email_invites_email_normalized
    check (email = lower(trim(email)))
);

create table public.categories (
  name text primary key,
  created_at timestamptz not null default now(),
  constraint categories_name_not_empty check (length(trim(name)) > 0)
);

create table public.resources (
  id bigint generated by default as identity primary key,
  title text not null,
  description text,
  type text not null check (type in ('audio', 'video', 'pdf', 'text')),
  archive_url text,
  text_content text,
  category text not null default 'General',
  created_at timestamptz not null default now(),
  constraint resources_title_not_empty check (length(trim(title)) > 0)
);

create index resources_created_at_idx
  on public.resources (created_at desc);
create index resources_type_idx on public.resources (type);
create index resources_category_idx on public.resources (category);

