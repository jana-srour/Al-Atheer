create or replace function public.create_profile_for_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  initial_name text;
  pending_admin boolean;
  normalized_email text;
begin
  normalized_email := lower(trim(coalesce(new.email, '')));
  initial_name := coalesce(
    nullif(trim(new.raw_user_meta_data ->> 'display_name'), ''),
    split_part(coalesce(new.email, ''), '@', 1)
  );

  select exists (
    select 1
    from public.admin_email_invites i
    where i.email = normalized_email
  ) into pending_admin;

  insert into public.profiles (id, display_name, is_admin)
  values (new.id, left(initial_name, 80), pending_admin)
  on conflict (id) do update
  set display_name = case
        when trim(public.profiles.display_name) = ''
          then excluded.display_name
        else public.profiles.display_name
      end,
      is_admin = public.profiles.is_admin or excluded.is_admin,
      updated_at = now();

  if pending_admin then
    delete from public.admin_email_invites
    where email = normalized_email;
  end if;

  return new;
end;
$$;

create trigger create_profile_after_signup
  after insert on auth.users
  for each row
  execute function public.create_profile_for_new_user();

insert into public.profiles (id, display_name)
select
  u.id,
  left(
    coalesce(
      nullif(trim(u.raw_user_meta_data ->> 'display_name'), ''),
      split_part(coalesce(u.email, ''), '@', 1)
    ),
    80
  )
from auth.users u
on conflict (id) do update
set display_name = case
  when trim(public.profiles.display_name) = ''
    then excluded.display_name
  else public.profiles.display_name
end;

create or replace function public.update_my_profile(new_display_name text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  normalized_name text := trim(coalesce(new_display_name, ''));
begin
  if auth.uid() is null then
    raise exception 'Sign in to update your profile.';
  end if;

  if normalized_name = '' or char_length(normalized_name) > 80 then
    raise exception 'Name must be between 1 and 80 characters.';
  end if;

  update public.profiles
  set display_name = normalized_name,
      updated_at = now()
  where id = auth.uid();

  if not found then
    raise exception 'Profile not found.';
  end if;
end;
$$;

create or replace function public.list_admin_access()
returns table (
  email text,
  display_name text,
  is_pending boolean,
  user_id uuid
)
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not public.is_current_user_admin() then
    raise exception 'Administrator access is required.';
  end if;

  return query
  select u.email::text, p.display_name, false, p.id
  from public.profiles p
  join auth.users u on u.id = p.id
  where p.is_admin
  union all
  select i.email, ''::text, true, null::uuid
  from public.admin_email_invites i
  where not exists (
    select 1
    from auth.users u
    join public.profiles p on p.id = u.id
    where lower(u.email) = i.email
      and p.is_admin
  )
  order by 1;
end;
$$;

create or replace function public.manage_admin_access(
  target_email text,
  enable_admin boolean
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  normalized_email text := lower(trim(coalesce(target_email, '')));
  target_user_id uuid;
  admin_count bigint;
begin
  if normalized_email = ''
      or normalized_email !~ '^[^@[:space:]]+@[^@[:space:]]+[.][^@[:space:]]+$' then
    raise exception 'Enter a valid email address.';
  end if;

  lock table public.profiles in exclusive mode;

  if not public.is_current_user_admin() then
    raise exception 'Administrator access is required.';
  end if;

  select u.id into target_user_id
  from auth.users u
  where lower(u.email) = normalized_email
  limit 1;

  if enable_admin then
    if target_user_id is null then
      insert into public.admin_email_invites (email, added_by)
      values (normalized_email, auth.uid())
      on conflict (email) do update set added_by = excluded.added_by;
      return;
    end if;

    insert into public.profiles (id, display_name, is_admin)
    select
      target_user_id,
      left(
        coalesce(
          nullif(trim(u.raw_user_meta_data ->> 'display_name'), ''),
          split_part(coalesce(u.email, ''), '@', 1)
        ),
        80
      ),
      true
    from auth.users u
    where u.id = target_user_id
    on conflict (id) do update
    set is_admin = true,
        updated_at = now();

    delete from public.admin_email_invites
    where email = normalized_email;
    return;
  end if;

  delete from public.admin_email_invites
  where email = normalized_email;

  if target_user_id is null then
    return;
  end if;

  if target_user_id = auth.uid() then
    raise exception 'You cannot remove your own administrator access.';
  end if;

  select count(*) into admin_count
  from public.profiles p
  where p.is_admin;

  if admin_count <= 1 and exists (
    select 1
    from public.profiles p
    where p.id = target_user_id
      and p.is_admin
  ) then
    raise exception 'The last administrator cannot be removed.';
  end if;

  update public.profiles
  set is_admin = false,
      updated_at = now()
  where id = target_user_id;
end;
$$;

