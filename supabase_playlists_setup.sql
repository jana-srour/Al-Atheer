-- Run in the Supabase SQL Editor to add mixed-media playlists without resetting data.
begin;

create table if not exists public.playlists (
  id bigint generated by default as identity primary key,
  title text not null,
  description text,
  created_at timestamptz not null default now(),
  constraint playlists_title_not_empty check (length(trim(title)) > 0)
);

create table if not exists public.playlist_items (
  playlist_id bigint not null
    references public.playlists (id) on delete cascade,
  resource_id bigint not null
    references public.resources (id) on delete cascade,
  sort_order integer not null default 0,
  primary key (playlist_id, resource_id)
);

create index if not exists playlist_items_order_idx
  on public.playlist_items (playlist_id, sort_order);

alter table public.playlists enable row level security;
alter table public.playlist_items enable row level security;

revoke all on public.playlists from public, anon, authenticated;
revoke all on public.playlist_items from public, anon, authenticated;
grant select on public.playlists to anon, authenticated;
grant insert, update, delete on public.playlists to authenticated;
grant usage, select on sequence public.playlists_id_seq to authenticated;
grant select on public.playlist_items to anon, authenticated;
grant insert, update, delete on public.playlist_items to authenticated;

drop policy if exists "Anyone can read playlists" on public.playlists;
create policy "Anyone can read playlists"
  on public.playlists for select to anon, authenticated
  using (true);

drop policy if exists "Admins can manage playlists" on public.playlists;
create policy "Admins can manage playlists"
  on public.playlists for all to authenticated
  using ((select public.is_current_user_admin()))
  with check ((select public.is_current_user_admin()));

drop policy if exists "Anyone can read playlist items" on public.playlist_items;
create policy "Anyone can read playlist items"
  on public.playlist_items for select to anon, authenticated
  using (true);

drop policy if exists "Admins can manage playlist items" on public.playlist_items;
create policy "Admins can manage playlist items"
  on public.playlist_items for all to authenticated
  using ((select public.is_current_user_admin()))
  with check ((select public.is_current_user_admin()));

create or replace function public.save_playlist_with_resources(
  p_playlist_id bigint,
  p_title text,
  p_description text,
  p_resource_ids bigint[]
)
returns bigint
language plpgsql
set search_path = ''
as $$
declare
  saved_playlist_id bigint;
  normalized_title text := trim(coalesce(p_title, ''));
begin
  if not public.is_current_user_admin() then
    raise exception 'Administrator access is required.';
  end if;
  if normalized_title = '' then
    raise exception 'Playlist title cannot be empty.';
  end if;

  if p_playlist_id is null then
    insert into public.playlists (title, description)
    values (normalized_title, nullif(trim(coalesce(p_description, '')), ''))
    returning id into saved_playlist_id;
  else
    update public.playlists
    set title = normalized_title,
        description = nullif(trim(coalesce(p_description, '')), '')
    where id = p_playlist_id
    returning id into saved_playlist_id;
    if saved_playlist_id is null then
      raise exception 'Playlist not found.';
    end if;
  end if;

  delete from public.playlist_items
  where playlist_id = saved_playlist_id;

  insert into public.playlist_items (playlist_id, resource_id, sort_order)
  select saved_playlist_id, selected.resource_id, selected.ordinality - 1
  from unnest(coalesce(p_resource_ids, '{}'::bigint[]))
    with ordinality as selected(resource_id, ordinality);

  return saved_playlist_id;
end;
$$;

revoke all on function public.save_playlist_with_resources(
  bigint, text, text, bigint[]
) from public, anon;
grant execute on function public.save_playlist_with_resources(
  bigint, text, text, bigint[]
) to authenticated;

notify pgrst, 'reload schema';
commit;
