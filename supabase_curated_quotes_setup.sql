-- Admin-managed daily wisdom. Uploaded text resources remain a separate source.
begin;

create table if not exists public.curated_quotes (
  id bigint generated by default as identity primary key,
  title text not null,
  quote text not null,
  source text not null default '',
  created_at timestamptz not null default now(),
  constraint curated_quotes_title_not_empty
    check (length(trim(title)) > 0),
  constraint curated_quotes_quote_not_empty
    check (length(trim(quote)) > 0)
);

alter table public.curated_quotes enable row level security;
revoke all on public.curated_quotes from public, anon, authenticated;
grant select on public.curated_quotes to anon, authenticated;
grant insert, update, delete on public.curated_quotes to authenticated;
grant usage, select on sequence public.curated_quotes_id_seq to authenticated;

drop policy if exists "Anyone can read curated quotes"
  on public.curated_quotes;
create policy "Anyone can read curated quotes"
  on public.curated_quotes
  for select
  to anon, authenticated
  using (true);

drop policy if exists "Admins can manage curated quotes"
  on public.curated_quotes;
create policy "Admins can manage curated quotes"
  on public.curated_quotes
  for all
  to authenticated
  using ((select public.is_current_user_admin()))
  with check ((select public.is_current_user_admin()));

notify pgrst, 'reload schema';
commit;
